-- SGN_STAGE_INSTANCE: этап экземпляра маршрута, создаётся при входе в этап. Хранит историю.

CREATE TABLE sgn_stage_instance (
    id                 NUMBER(19)               GENERATED ALWAYS AS IDENTITY,
    route_instance_id  NUMBER(19)               NOT NULL,
    stage_key          VARCHAR2(100 CHAR)       NOT NULL,
    state              VARCHAR2(20 CHAR)        NOT NULL,
    request_id         VARCHAR2(64 CHAR)        NOT NULL,
    requested_at       TIMESTAMP WITH TIME ZONE,
    deadline_at        TIMESTAMP WITH TIME ZONE,
    finished_at        TIMESTAMP WITH TIME ZONE,
    reason             VARCHAR2(2000 CHAR),
    CONSTRAINT sgn_stage_instance_pk PRIMARY KEY (id),
    CONSTRAINT sgn_stage_instance_request_uk UNIQUE (request_id),
    CONSTRAINT sgn_stage_instance_route_fk
        FOREIGN KEY (route_instance_id) REFERENCES sgn_route_instance (id),
    CONSTRAINT sgn_stage_instance_state_ck
        CHECK (state IN ('PENDING', 'REQUESTED', 'DONE', 'REJECTED', 'EXPIRED', 'FAILED')),
    CONSTRAINT sgn_stage_instance_requested_ck
        CHECK (state <> 'REQUESTED' OR (requested_at IS NOT NULL AND deadline_at IS NOT NULL))
);

CREATE INDEX sgn_stage_instance_route_ix ON sgn_stage_instance (route_instance_id);

ALTER TABLE sgn_route_instance ADD CONSTRAINT sgn_route_instance_stage_fk
    FOREIGN KEY (current_stage_id) REFERENCES sgn_stage_instance (id);

COMMENT ON TABLE sgn_stage_instance IS 'Stage instance: one row per entered stage of a route instance.';
COMMENT ON COLUMN sgn_stage_instance.stage_key IS 'Stage key from the route definition.';
COMMENT ON COLUMN sgn_stage_instance.state IS 'PENDING, REQUESTED, DONE, REJECTED, EXPIRED, FAILED.';
COMMENT ON COLUMN sgn_stage_instance.request_id IS 'Signing request id, generated by the service on stage entry.';
COMMENT ON COLUMN sgn_stage_instance.deadline_at IS 'requested_at + stage timeout.';
COMMENT ON COLUMN sgn_stage_instance.reason IS 'Rejection or error reason.';
